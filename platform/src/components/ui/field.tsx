/**
 * field.tsx
 *
 * Generated from shadcn's `base-vega` field registry entry, then customized. Divergences from
 * pristine, and why:
 *
 * - **Disabled label text is `text-disabled-text`, not `opacity-50`** (`FieldLabel`, `FieldTitle`).
 *   `.claude/rules/components-rules.md` § Forms and DESIGN.md §6 both require a flat token
 *   replacement for disabled fields rather than a dimmed version of the enabled colour — the same
 *   principle Buttons follow. Pristine shadcn dims.
 * - **`FieldGroup` gaps at `gap-6` (24px), not `gap-7` (28px).** DESIGN.md §7 sets 24px as the gap
 *   between clusters of related components, and 28px is off the 4px scale
 *   (`.claude/skills/add-ui-component/SKILL.md` § Rules). `ui/**` is exempt from
 *   `local/no-off-scale-spacing`, so nothing would have caught this.
 * - `"use client"` dropped (Vite SPA, no RSC — `components.json` has `"rsc": false`).
 * - Registry import paths rewritten to `@framework/*`.
 *
 * Deliberately left as pristine: the sub-pixel negative margins in `FieldDescription` /
 * `FieldSeparator` (`-mt-1.5`, `-my-2`, `h-5`). Those are optical tuning against adjacent text,
 * which is exactly the case `ui/**`'s off-scale-spacing exemption exists for — rounding them to the
 * 4px scale would visibly misalign the text they were measured against.
 *
 * Note on the invalid/disabled API: the variants key off `data-[invalid=true]` and
 * `data-[disabled=true]`, so write `<Field data-invalid>` / `<Field data-disabled>` — JSX stringifies
 * an implicit boolean to `"true"`, which is what the selectors match. `data-invalid` styles the
 * label and description; the control still needs its own `aria-invalid`.
 */

import * as React from "react";
import { cva, type VariantProps } from "class-variance-authority";

import { cn } from "@framework/lib/shadcn/shadcn-utils";
import { Label } from "@framework/components/ui/label";
import { Separator } from "@framework/components/ui/separator";

